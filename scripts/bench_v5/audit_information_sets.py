#!/usr/bin/env python3
"""Audit information parity for the low->high Ditto comparison."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def load(path: Path):
    if path.suffix == ".json":
        return json.loads(path.read_text(encoding="utf-8"))
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()
            if line.strip()]


def index(rows):
    return {row["sample_id"]: row for row in rows}


def count_mp4(path: Path) -> int:
    return len(list(path.glob("*.mp4"))) if path.exists() else 0


def first_meta(path: Path):
    files = sorted(path.glob("*.meta.json"))
    return load(files[0]) if files else {}


def protocol(meta):
    response = meta.get("response") or {}
    return {
        "variant": meta.get("variant"),
        "seed": meta.get("seed"),
        "resolution": response.get("resolution"),
        "frames": response.get("num_frames"),
        "steps": response.get("num_inference_steps"),
        "lora": response.get("lora_paths"),
    }


def means(path: Path, arms):
    rows = load(path)
    result = {}
    for arm in arms:
        values = [row[arm]["profile_error"] for row in rows
                  if row.get("provenance") == "low_high_cost" and arm in row]
        if values:
            result[arm] = (len(values), sum(values) / len(values))
    return result


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", type=Path, default=Path(__file__).resolve().parents[2])
    ap.add_argument("--out", type=Path,
                    default=Path("out/bench_v5/INFORMATION_AUDIT.md"))
    args = ap.parse_args()
    root = args.project

    archived = index(load(root / "归档_extract/sample_index.json"))
    expert = index(load(root / "scripts/bench_v4/data/instructions_expert.jsonl"))
    intents = index(load(root / "scripts/bench_v4/data/instructions_intent.jsonl"))
    grounded = index(load(root / "scripts/bench_v4/data/instructions_grounded_clean48.jsonl"))
    exact_expert = sum(
        sid in archived and row.get("instruction") == archived[sid].get("instruction")
        for sid, row in expert.items()
    )
    forbidden_grounded_fields = {
        "target_video", "target_high", "high_video", "reference_video",
        "target_caption", "high_caption",
    }
    grounded_target_fields = sorted({
        field for row in grounded.values()
        for field in forbidden_grounded_fields.intersection(row)
    })
    intent_sources = sorted({str(row.get("source", "")) for row in intents.values()})
    scores = means(root / "scripts/bench_v5/data/scores_final.jsonl",
                   ["direct_intent", "g0_grounded_clean", "pub_Ditto"])

    rows = [
        ("direct_intent", root / "out/bench_v4/runs/direct_intent"),
        ("g0_grounded_clean", root / "out/bench_v5/runs/g0_grounded_clean"),
        ("direct_expert_v5", root / "out/bench_v5/runs/direct_expert_v5"),
    ]
    direct_protocol = protocol(first_meta(rows[0][1]))
    g0_protocol = protocol(first_meta(rows[1][1]))
    shared_protocol_fields = ("variant", "seed", "resolution", "frames", "steps", "lora")
    mismatches = [field for field in shared_protocol_fields
                  if direct_protocol.get(field) != g0_protocol.get(field)]
    if exact_expert != len(expert):
        raise SystemExit(f"expert/archive prompt mismatch: {exact_expert}/{len(expert)}")
    if grounded_target_fields:
        raise SystemExit(f"grounded prompt data contains target fields: "
                         f"{grounded_target_fields}")
    if mismatches:
        raise SystemExit(f"direct/g0 render protocol mismatch: {mismatches}")
    lines = [
        "# Information-parity audit: Ditto comparison",
        "",
        "Generated by `scripts/bench_v5/audit_information_sets.py`.",
        "",
        "## Conclusion",
        "",
        "The agent and `direct_intent` use the same Ditto backend. The archived "
        "`pub_Ditto` row is not an information-matched baseline: its instruction "
        "comes from the expert bundle, and `out/REPORT_ALL.md` §0.1 states that "
        "the expert instruction was written after viewing both low and high videos.",
        "It is therefore an answer-aware reference, not a fair control for an agent "
        "restricted to low video plus a one-line intent.",
        "",
        "The fair causal comparison is `g0_grounded_clean` versus `direct_intent`. "
        "`pub_Ditto` measures the remaining gap to an answer-aware full-instruction "
        "reference and must be reported separately.",
        "",
        "## Evidence",
        "",
        f"- Archived sample rows: **{len(archived)}**.",
        f"- Archived rows carrying a Ditto method path: "
        f"**{sum('Ditto' in (row.get('methods') or {}) for row in archived.values())}**.",
        f"- Local archived Ditto videos: "
        f"**{count_mp4(root / '归档_extract/methods/Ditto')}**.",
        f"- Expert instructions exactly matching archived instructions: "
        f"**{exact_expert}/{len(expert)}**.",
        f"- One-line intent rows: **{len(intents)}**; source values: "
        f"`{', '.join(intent_sources)}`.",
        f"- Grounded-clean rows used by g0: **{len(grounded)}**; audited target-"
        f"side fields found: **{grounded_target_fields or 'none'}**.",
        "",
        "The prompt provenance is also recorded in `out/REPORT_ALL.md` and "
        "`out/PROMPT_WALKTHROUGH.md`.",
        "",
        "## Ditto protocol metadata",
        "",
        "| arm | variant | seed | resolution | frames | steps | LoRA | renders |",
        "|---|---|---:|---|---:|---:|---|---:|",
    ]
    for name, directory in rows:
        p = protocol(first_meta(directory))
        lines.append(
            f"| `{name}` | `{p.get('variant')}` | {p.get('seed')} | "
            f"`{p.get('resolution')}` | {p.get('frames')} | {p.get('steps')} | "
            f"`{', '.join(p.get('lora') or [])}` | {count_mp4(directory)} |"
        )
    lines += [
        "",
        "The direct and g0 rows use the same `wan14b+dittolora` backend, seed 42, "
        "832x480 and 20 steps. The local expert arm has only one completed render "
        "and is not a statistical result.",
        "",
        "## Current low-high scores",
        "",
        "| arm | n | profile_error | information condition |",
        "|---|---:|---:|---|",
    ]
    labels = {
        "direct_intent": "low + one-line intent",
        "g0_grounded_clean": "low frames + one-line intent, agent grounding",
        "pub_Ditto": "archived output + answer-aware expert instruction",
    }
    for arm in ("direct_intent", "g0_grounded_clean", "pub_Ditto"):
        if arm in scores:
            n, value = scores[arm]
            lines.append(f"| `{arm}` | {n} | {value:.4f} | {labels[arm]} |")
    lines += [
        "",
        "Do not sort these three rows as one information-neutral leaderboard. "
        "Use `direct_intent` as the primary same-information baseline and label "
        "`pub_Ditto` as an answer-aware full-instruction reference.",
        "",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
